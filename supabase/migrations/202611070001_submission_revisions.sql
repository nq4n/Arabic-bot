-- حفظ تاريخ مراجعات الكتابة في مهام التقييم.
--
-- يكتب الطالب نصه ويقيّمه الذكاء الاصطناعي، ثم يُسمح له بتعديل واحد
-- وإعادة التقييم (محاولتان كحد أقصى لكل مهمة). قبل هذا التحديث كان
-- التعديل يكتب فوق النص الأول فيضيع، فلا يستطيع المعلم المقارنة بين
-- ما كتبه الطالب أولاً وما عدّله بعد تقييم الذكاء الاصطناعي.
--
-- العمود الجديد يحفظ النسخ السابقة بالترتيب (الأقدم أولاً). تبقى
-- الأعمدة الحالية (submission_data, ai_response, ai_grade) حاملةً
-- للنسخة الأحدث دائماً، ويحمل revisions النسخة/النسخ الأقدم.
-- كل عنصر: { submission_data, ai_response, ai_grade, created_at }.
alter table public.submissions
  add column if not exists revisions jsonb not null default '[]'::jsonb;
