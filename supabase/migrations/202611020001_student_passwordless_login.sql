-- تسجيل دخول الطلاب باسم المستخدم فقط (بدون كلمة مرور).
--
-- الطلاب لم يعودوا يملكون كلمة مرور يستخدمونها في الدخول (تُولَّد لهم
-- كلمة مرور عشوائية عند الإنشاء ولا تُعرض لأحد)، لذلك لا معنى لمطالبتهم
-- بتغييرها عند أول دخول. هذا التحديث يزيل العلم عن الحسابات الحالية.
update public.profiles
set must_change_password = false
where role = 'student'
  and must_change_password is distinct from false;

